def normalize_language(value: object) -> str:
    normalized = str(value or "").strip().lower().replace("_", "-")
    if normalized in {"zh", "zh-cn", "zh-hans", "zh-hans-cn"}:
        return "zh-CN"
    return "en"


def request_language(request: object) -> str:
    cookies = getattr(request, "cookies", {})
    value = cookies.get(LANGUAGE_COOKIE, DEFAULT_LANGUAGE) if isinstance(cookies, Mapping) else ""
    return normalize_language(value)


def language_messages(request: object) -> dict[str, str]:
    return MESSAGES[request_language(request)]


def translate(language: str, key: str, **values: object) -> str:
    message = MESSAGES.get(language, MESSAGES[DEFAULT_LANGUAGE]).get(key)
    if message is None:
        message = MESSAGES[DEFAULT_LANGUAGE].get(key, key)
    try:
        return message.format(**values)
    except (KeyError, ValueError):
        return message


@pass_context
def template_translate(context: Mapping[str, Any], key: str, **values: object) -> str:
    return translate(request_language(context.get("request")), key, **values)
